/** 根據漢字特徵推測吉凶（針對不在資料庫中的字） */
function analyzeCharacterStructure(char: string): { fortune: '吉' | '中' | '凶'; structure: string } {
  const code = char.charCodeAt(0);

  // 吉祥字根
  const auspiciousParts = ['福', '吉', '龍', '鳳', '金', '玉', '日', '月', '春', '喜', '德', '善', '安', '樂'];
  const cautiousParts = ['刀', '刂', '血', '鬼', '死', '病', '疒', '傷', '敗', '失', '亡'];

  for (const part of auspiciousParts) {
    if (char.includes(part)) {
      return { fortune: '吉', structure: `字中含有「${part}」吉祥部件，整體偏吉。` };
    }
  }
  for (const part of cautiousParts) {
    if (char.includes(part)) {
      return { fortune: '凶', structure: `字中含有「${part}」凶險部件，整體偏凶，宜謹慎。` };
    }
  }

  // 筆畫推測（簡易版：筆畫少為清吉，多為繁難）
  const strokeCount = estimateStrokeCount(code);
  if (strokeCount <= 5) return { fortune: '吉', structure: '筆畫簡潔，氣勢清朗，屬吉。' };
  if (strokeCount <= 12) return { fortune: '中', structure: '筆畫適中，結構均衡，屬中平。' };
  return { fortune: '中', structure: '筆畫較多，結構繁複，建議靜觀其變。' };
}

/** 簡易筆畫估算（基於 Unicode 區段粗略推算） */
function estimateStrokeCount(code: number): number {
  // CJK Unified Ideographs: U+4E00 - U+9FFF
  // 粗略估算：常用字約 8-12 畫，生僻字較多
  if (code >= 0x4E00 && code <= 0x9FFF) {
    return 8 + ((code - 0x4E00) % 12);
  }
  // CJK Extension A: U+3400 - U+4DBF
  if (code >= 0x3400 && code <= 0x4DBF) {
    return 12 + ((code - 0x3400) % 10);
  }
  return 10; // 預設
}

/** 對任意漢字進行測字分析 */
export function analyzeCharacter(char: string, question?: string): CharacterAnalysis {
  // 先查詢資料庫
  if (CHARACTER_DATABASE[char]) {
    const result = { ...CHARACTER_DATABASE[char] };
    if (question) {
      result.meaning = `問：「${question}」\n\n${result.meaning}`;
    }
    return result;
  }

  // 不在資料庫中，進行結構分析推斷
  const { fortune, structure } = analyzeCharacterStructure(char);

  const questionPrefix = question ? `問：「${question}」\n\n` : '';

  const meanings: Record<string, string> = {
    '吉': `${questionPrefix}此字整體氣象吉祥，結構清朗有力。問事可成，但需努力推進、把握時機。`,
    '中': `${questionPrefix}此字結構平穩，無大喜也無大憂。目前一切尚在醞釀，靜待時機、做好準備最為重要。`,
    '凶': `${questionPrefix}此字暗含險阻之象，宜先求穩再求進。凡事三思而後行，暫時不宜冒險或做大變動。`,
  };

  const advices: Record<string, string> = {
    '吉': '順勢而為，但勿忘風險管理。好運時更要步步為營。',
    '中': '保持耐心，不要急於求成。穩中求進是最好的策略。',
    '凶': '謹慎行事，多聽取他人意見。保守應對，等待時機好轉。',
  };

  return {
    meaning: meanings[fortune],
    structure,
    fortune,
    fortuneLabel: fortune,
    advice: advices[fortune],
  };
}
