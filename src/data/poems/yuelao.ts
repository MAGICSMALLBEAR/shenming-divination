const CN_DIGITS = ['〇', '一', '二', '三', '四', '五', '六', '七', '八', '九'];

function lotLabel(n: number): string {
  if (n === 100) return '第一百籤';
  if (n < 10) return `第${CN_DIGITS[n]}籤`;
  const tens = Math.floor(n / 10);
  const ones = n % 10;
  return `第${tens === 1 ? '' : CN_DIGITS[tens]}十${ones ? CN_DIGITS[ones] : ''}籤`;
}

