// 根據神明ID取得祝福語集
export function getGodBlessingSet(godId: number): GodBlessingSet | null {
  return GOD_BLESSINGS.find(b => b.godId === godId) ?? null;
}

// 取得隨機祝福語
export function getRandomBlessing(godId: number): string {
  const set = getGodBlessingSet(godId);
  if (!set) return '';
  const idx = Math.floor(Math.random() * set.blessings.length);
  return set.blessings[idx];
}

// 取得每日固定祝福語（根據日期選定，確保同一天同神明拿到同一句）
export function getDailyBlessing(godId: number): string {
  const set = getGodBlessingSet(godId);
  if (!set) return '';
  const day = new Date().getDate();
  const idx = day % set.blessings.length;
  return set.blessings[idx];
}

